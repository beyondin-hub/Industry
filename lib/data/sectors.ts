function cat(
  sector_slug: SectorSlug,
  slug: string,
  nombre: string,
  descripcion: string,
  icono: string,
  orden: number,
  destacada: boolean,
): SectorCategory {
  const color = sector_slug === "medical" ? "#0E7490" : "#6D28D9";
  return { id: `cat-${sector_slug}-${slug}`, sector_slug, slug, nombre, descripcion, icono, color_badge: color, orden, destacada };
}

export function categoriesForSector(slug: string): SectorCategory[] {
  return SECTOR_CATEGORIES.filter((c) => c.sector_slug === slug).sort((a, b) => a.orden - b.orden);
}

